#!/bin/bash

# ==============================================================================
# Автоматичний скрипт для схлопування міграцій одразу для 2 застосунків
# ==============================================================================

echo "🚀 Запускаємо автоматичний майстер схлопування міграцій!"
echo "---------------------------------------------------"

# --- ЗАСТОСУНОК 1: INVENTORY ---
echo "📦 Застосунок 1: INVENTORY"
read -p "Введи номер останньої міграції для inventory (наприклад, 0008) або натисни Enter, щоб пропустити: " INV_END

if [ -n "$INV_END" ]; then
  echo "🔄 Схлопуємо inventory з 0001 до $INV_END..."
  docker-compose exec app python manage.py squashmigrations inventory 0001 $INV_END
else
  echo "⚠️ Пропущено схлопування inventory."
fi

echo "---------------------------------------------------"

# --- ЗАСТОСУНОК 2: USERS ---
echo "👥 Застосунок 2: USERS"
read -p "Введи номер останньої міграції для users (наприклад, 0005) або натисни Enter, щоб пропустити: " USR_END

if [ -n "$USR_END" ]; then
  echo "🔄 Схлопуємо users з 0001 до $USR_END..."
  docker-compose exec app python manage.py squashmigrations users 0001 $USR_END
else
  echo "⚠️ Пропущено схлопування users."
fi

echo "---------------------------------------------------"
echo "✅ Роботу завершено! Нові Baseline-міграції успішно згенеровані."